create policy "admins can upload reference image objects"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'reference-images'
  and (storage.foldername(name))[1] = any (
    array['konyha', 'gardrob', 'eloszoba', 'furdo', 'nappali', 'egyedi']
