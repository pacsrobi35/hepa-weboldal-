create table public.reference_images (
  id bigint generated by default as identity primary key,
  category text not null,
  storage_path text not null unique,
  original_name text not null,
  alt_text text not null default '',
  sort_order integer not null default 0,
  is_published boolean not null default true,
  uploaded_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint reference_images_category_check check (
    category = any (array['konyha', 'gardrob', 'eloszoba', 'furdo', 'nappali', 'egyedi'])
  ),
  constraint reference_images_alt_text_length_check check (char_length(alt_text) <= 200),
  constraint reference_images_sort_order_check check (sort_order >= 0)
);

create index reference_images_gallery_idx
  on public.reference_images (category, is_published, sort_order, created_at desc);

alter table public.reference_images enable row level security;

grant select on table public.reference_images to anon;
grant select, insert, update, delete on table public.reference_images to authenticated;
grant usage, select on sequence public.reference_images_id_seq to authenticated;

create policy "published reference images are public"
on public.reference_images
for select
to anon, authenticated
using (is_published);

create policy "admins can read all reference images"
on public.reference_images
for select
to authenticated
using (
  exists (
    select 1
    from public.admin_users
    where admin_users.user_id = (select auth.uid())
  )
);

create policy "admins can insert reference images"
on public.reference_images
for insert
to authenticated
with check (
  uploaded_by = (select auth.uid())
  and exists (
    select 1
    from public.admin_users
    where admin_users.user_id = (select auth.uid())
  )
);

create policy "admins can update reference images"
on public.reference_images
for update
to authenticated
using (
  exists (
    select 1
    from public.admin_users
    where admin_users.user_id = (select auth.uid())
  )
)
with check (
  exists (
    select 1
    from public.admin_users
    where admin_users.user_id = (select auth.uid())
  )
